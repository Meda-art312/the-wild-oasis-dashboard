-- Run once in the SQL Editor of a NEW Supabase project.
-- Disable public signups in Authentication settings before exposing this app.
begin;

create table public.cabins (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  "maxCapacity" integer not null check ("maxCapacity" > 0),
  "regularPrice" numeric not null check ("regularPrice" > 0),
  discount numeric not null default 0 check (discount >= 0 and discount <= "regularPrice"),
  description text not null default '',
  image text not null
);

create table public.guests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "fullName" text not null,
  email text not null,
  "nationalID" text,
  nationality text,
  "countryFlag" text
);

create table public.bookings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "startDate" timestamptz not null,
  "endDate" timestamptz not null,
  "numNights" integer not null check ("numNights" > 0),
  "numGuests" integer not null check ("numGuests" > 0),
  "cabinPrice" numeric not null,
  "extrasPrice" numeric not null default 0,
  "totalPrice" numeric not null,
  status text not null check (status in ('unconfirmed', 'checked-in', 'checked-out')),
  "hasBreakfast" boolean not null default false,
  "isPaid" boolean not null default false,
  observations text not null default '',
  "cabinId" bigint not null references public.cabins(id),
  "guestId" bigint not null references public.guests(id),
  check ("endDate" > "startDate")
);

create table public.settings (
  id bigint primary key check (id = 1),
  created_at timestamptz not null default now(),
  "minBookingLength" integer not null check ("minBookingLength" > 0),
  "maxBookingLength" integer not null check ("maxBookingLength" >= "minBookingLength"),
  "maxGuestsPerBooking" integer not null check ("maxGuestsPerBooking" > 0),
  "breakfastPrice" numeric not null check ("breakfastPrice" >= 0)
);
insert into public.settings values (1, now(), 3, 30, 10, 15);

create index on public.bookings ("startDate");
create index on public.bookings (created_at);
create index on public.bookings ("cabinId");
create index on public.bookings ("guestId");

alter table public.cabins enable row level security;
alter table public.guests enable row level security;
alter table public.bookings enable row level security;
alter table public.settings enable row level security;

revoke all on public.cabins, public.guests, public.bookings, public.settings from anon;
grant select, insert, update, delete on public.cabins, public.guests, public.bookings to authenticated;
grant select, update on public.settings to authenticated;
grant usage, select on sequence public.cabins_id_seq, public.guests_id_seq, public.bookings_id_seq to authenticated;

-- This is a private staff app: all accounts are trusted staff created by the owner.
create policy "Staff manage cabins" on public.cabins for all to authenticated using (true) with check (true);
create policy "Staff manage guests" on public.guests for all to authenticated using (true) with check (true);
create policy "Staff manage bookings" on public.bookings for all to authenticated using (true) with check (true);
create policy "Staff read settings" on public.settings for select to authenticated using (true);
create policy "Staff update settings" on public.settings for update to authenticated using (true) with check (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('cabin-images', 'cabin-images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp', 'image/gif']),
  ('avatars', 'avatars', true, 5242880, array['image/jpeg', 'image/png', 'image/webp', 'image/gif']);

create policy "Staff upload cabin images" on storage.objects for insert to authenticated
  with check (bucket_id = 'cabin-images');
create policy "Staff read image records" on storage.objects for select to authenticated
  using (bucket_id in ('cabin-images', 'avatars'));
create policy "Staff remove cabin images" on storage.objects for delete to authenticated
  using (bucket_id = 'cabin-images');
create policy "Upload own avatar" on storage.objects for insert to authenticated
  with check (bucket_id = 'avatars' and name like 'avatar-' || (select auth.uid())::text || '-%');

commit;
